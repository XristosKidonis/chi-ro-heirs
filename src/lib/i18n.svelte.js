export const idioma = () => (usuario.ajustes.idioma === 'en' ? 'en' : 'es');
export const locale = () => (idioma() === 'en' ? 'en-US' : 'es');

export function t(clave, p = {}) {
  const d = idioma() === 'en' ? EN : ES;
  let s = d[clave] ?? ES[clave] ?? clave;
  for (const [k, v] of Object.entries(p)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

export const fecha = (ms, opciones = { day: 'numeric', month: 'short' }) => new Date(ms).toLocaleDateString(locale(), opciones);
